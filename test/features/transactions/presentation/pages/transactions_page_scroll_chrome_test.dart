import 'package:flutter_bloc/flutter_bloc.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:mocktail/mocktail.dart';

import '../../../accounts/account_fixtures.dart';
import '../../../categories/presentation/widgets/pump_widget.dart';
import '../../transaction_fixtures.dart';

class MockTransactionsListCubit extends MockCubit<TransactionsListState>
    implements TransactionsListCubit {}

/// The Movimientos account-chips row + Period Stepper are scroll-driven chrome
/// (2026-11-07): they collapse with a 200ms height+fade (`ScrollAwareCollapsible`)
/// on scroll down and come back on scroll up, driven by the same
/// `ScrollAwareFabVisibility` signal as the FAB. The search row stays pinned.
///
/// These are widget-level assertions on the collapse mechanics (the at-rest
/// pixels are guarded separately by the committed goldens, which must not
/// change); the golden suite is NOT regenerated by this file.
void main() {
  late MockTransactionsListCubit cubit;

  final accounts = [
    buildAccountWithBalance(
      account: buildAccount(id: 'acc-1', name: 'Efectivo'),
      balanceMinor: 450050,
    ),
    buildAccountWithBalance(
      account: buildAccount(id: 'acc-2', name: 'Bancolombia'),
      balanceMinor: 20000,
    ),
  ];

  List<TransactionWithDetails> buildManyItems() => [
        for (var i = 0; i < 40; i++)
          TransactionWithDetails(
            transaction: buildTransaction(
              id: 'tx-$i',
              amountMinor: 10000 + i,
              date: DateTime(2026, 7, 15).subtract(Duration(days: i)),
            ),
            accountName: 'Efectivo',
            categoryName: 'Comida',
            categoryIcon: 'utensils',
            categoryColor: 'coral',
          ),
      ];

  TransactionsListState readyWithData() => TransactionsListState(
        status: TransactionsListStatus.ready,
        filter: TransactionFilter(),
        items: buildManyItems(),
        accounts: accounts,
      );

  setUpAll(() {
    registerFallbackValue(TransactionFilter());
  });

  setUp(() {
    cubit = MockTransactionsListCubit();
    when(() => cubit.updateFilter(any())).thenAnswer((_) async {});
  });

  Future<void> pumpPage(
    WidgetTester tester, {
    TransactionsListState? state,
  }) async {
    when(() => cubit.state).thenReturn(state ?? readyWithData());
    await tester.pumpAppWidget(
      BlocProvider<TransactionsListCubit>.value(
        value: cubit,
        child: TransactionsPage(
          onAddTransaction: (_) {},
          onOpenTransaction: (_) async => null,
        ),
      ),
    );
    await tester.pumpAndSettle();
  }

  // The collapsible's own animation layers are the outermost ones of each
  // type under it (its `child` is rendered inside them), so `.first` picks
  // them deterministically even if a descendant uses `Opacity`/`Align` too.

  /// The collapsible's fade layer.
  double chromeOpacity(WidgetTester tester) => tester
      .widget<Opacity>(
        find
            .descendant(
              of: find.byType(ScrollAwareCollapsible),
              matching: find.byType(Opacity),
            )
            .first,
      )
      .opacity;

  /// The collapsible's animated height factor: 1 at rest, 0 collapsed.
  double chromeHeightFactor(WidgetTester tester) => tester
      .widget<Align>(
        find
            .descendant(
              of: find.byType(ScrollAwareCollapsible),
              matching: find.byType(Align),
            )
            .first,
      )
      .heightFactor!;

  /// Whether the collapsible is currently clipping its child's paint.
  Clip chromeClip(WidgetTester tester) => tester
      .widget<ClipRect>(
        find
            .descendant(
              of: find.byType(ScrollAwareCollapsible),
              matching: find.byType(ClipRect),
            )
            .first,
      )
      .clipBehavior;

  double fabOpacity(WidgetTester tester) => tester
      .widget<AnimatedOpacity>(
        find.descendant(
          of: find.byType(ScrollAwareFab),
          matching: find.byType(AnimatedOpacity),
        ),
      )
      .opacity;

  // The chrome block's own rendered height: 0 once collapsed (heightFactor 0),
  // the full chips+stepper height at rest.
  double chromeHeight(WidgetTester tester) =>
      tester.getSize(find.byType(ScrollAwareCollapsible)).height;

  Future<void> scrollDown(WidgetTester tester) async {
    await tester.drag(find.byType(ListView), const Offset(0, -400));
    await tester.pump();
    // Past the 200ms collapse animation.
    await tester.pump(const Duration(milliseconds: 250));
  }

  Future<void> scrollUp(WidgetTester tester) async {
    await tester.drag(find.byType(ListView), const Offset(0, 400));
    await tester.pump();
    await tester.pump(const Duration(milliseconds: 250));
  }

  testWidgets(
    'at rest the account chips row and Period Stepper are expanded and visible',
    (tester) async {
      await pumpPage(tester);

      expect(chromeOpacity(tester), 1);
      expect(chromeHeightFactor(tester), 1);
      expect(chromeHeight(tester), greaterThan(0));
      expect(fabOpacity(tester), 1);

      // At rest the block must NOT clip: the Period Stepper's drop shadow
      // overflows its own box and the committed goldens capture it. Clipping
      // while visible+idle was a real at-rest regression (40 goldens), so this
      // guards it directly.
      expect(chromeClip(tester), Clip.none);

      // Both pieces of chrome are mounted and showing their real content.
      expect(find.byType(AccountFilterChipRow), findsOneWidget);
      expect(
        find.descendant(
          of: find.byType(AccountFilterChipRow),
          matching: find.text('Efectivo'),
        ),
        findsOneWidget,
      );
      expect(find.byType(PeriodStepper), findsOneWidget);
      expect(
        tester.widget<PeriodStepper>(find.byType(PeriodStepper)).label,
        isNotNull,
      );
    },
  );

  testWidgets(
    'scrolling the list down collapses the chrome (opacity 0, height 0) and '
    'hides the FAB through the shared signal',
    (tester) async {
      await pumpPage(tester);
      final stepperLabel =
          tester.widget<PeriodStepper>(find.byType(PeriodStepper)).label;
      expect(stepperLabel, isNotNull);

      await scrollDown(tester);

      // Collapsed by both mechanisms the animation drives.
      expect(chromeOpacity(tester), 0);
      expect(chromeHeightFactor(tester), 0);
      expect(chromeHeight(tester), 0);
      // While hidden the block clips its (zero-height) child.
      expect(chromeClip(tester), Clip.hardEdge);

      // The FAB shares the same `ScrollAwareFabVisibility` signal.
      expect(fabOpacity(tester), 0);

      // The chrome is hidden, not unmounted: it stays in the tree (so the
      // chip row keeps its own state) but renders fully transparent.
      expect(find.byType(AccountFilterChipRow), findsOneWidget);
      expect(
        find.descendant(
          of: find.byType(AccountFilterChipRow),
          matching: find.text('Efectivo'),
        ),
        findsOneWidget,
      );
      expect(find.byType(PeriodStepper), findsOneWidget);
      expect(find.text(stepperLabel!), findsOneWidget);
    },
  );

  testWidgets(
    'scrolling back up reveals the chrome (opacity and height factor back to 1)',
    (tester) async {
      await pumpPage(tester);

      await scrollDown(tester);
      expect(chromeOpacity(tester), 0);
      expect(chromeHeightFactor(tester), 0);

      await scrollUp(tester);

      expect(chromeOpacity(tester), 1);
      expect(chromeHeightFactor(tester), 1);
      expect(chromeHeight(tester), greaterThan(0));
      // Fully revealed and idle again: painting is unclipped once more.
      expect(chromeClip(tester), Clip.none);
      expect(fabOpacity(tester), 1);
      expect(find.byType(AccountFilterChipRow), findsOneWidget);
      expect(find.byType(PeriodStepper), findsOneWidget);
    },
  );

  testWidgets(
    'the search row stays pinned at the same position while the list scrolls',
    (tester) async {
      await pumpPage(tester);

      final searchRectBefore = tester.getRect(find.byType(TextField));
      expect(find.text('Buscar por nota'), findsOneWidget);
      // Pinned = literally not wrapped by the collapsing fade.
      expect(
        find.ancestor(
          of: find.byType(TextField),
          matching: find.byType(Opacity),
        ),
        findsNothing,
      );

      await scrollDown(tester);

      // Chrome above it collapsed and the list scrolled, yet the search row
      // renders at the exact same spot and is still queryable.
      expect(chromeOpacity(tester), 0);
      expect(tester.getRect(find.byType(TextField)), searchRectBefore);
      expect(find.text('Buscar por nota'), findsOneWidget);
      expect(find.byType(TextField), findsOneWidget);
    },
  );

  testWidgets(
    'hidden chrome ignores taps: tapping where a chip was does not change the '
    'filter',
    (tester) async {
      await pumpPage(tester);

      // Where the "Efectivo" account chip sits while the chrome is visible.
      final chipCenter = tester
          .getRect(
            find.descendant(
              of: find.byType(AccountFilterChipRow),
              matching: find.text('Efectivo'),
            ),
          )
          .center;

      await scrollDown(tester);
      expect(chromeOpacity(tester), 0);

      // Collapsed chrome is both pointer- and semantics-inert.
      final ignorePointer = tester.widget<IgnorePointer>(
        find
            .descendant(
              of: find.byType(ScrollAwareCollapsible),
              matching: find.byType(IgnorePointer),
            )
            .first,
      );
      expect(ignorePointer.ignoring, isTrue);
      final excludeSemantics = tester.widget<ExcludeSemantics>(
        find
            .descendant(
              of: find.byType(ScrollAwareCollapsible),
              matching: find.byType(ExcludeSemantics),
            )
            .first,
      );
      expect(excludeSemantics.excluding, isTrue);

      // The old chip location now belongs to the list, never to the hidden
      // account chip: a chip tap would call `updateFilter`.
      await tester.tapAt(chipCenter);
      await tester.pump();
      verifyNever(() => cubit.updateFilter(any()));
    },
  );

  testWidgets(
    'the empty state also renders the chrome expanded at rest',
    (tester) async {
      await pumpPage(
        tester,
        state: TransactionsListState(
          status: TransactionsListStatus.ready,
          filter: TransactionFilter(),
          accounts: accounts,
        ),
      );

      expect(chromeOpacity(tester), 1);
      expect(chromeHeightFactor(tester), 1);
      expect(chromeClip(tester), Clip.none);
      expect(find.byType(AccountFilterChipRow), findsOneWidget);
      expect(find.byType(PeriodStepper), findsOneWidget);
      expect(find.text('Buscar por nota'), findsOneWidget);
    },
  );
}
